CREATE TABLE INSURANCEPOLICY (
    Policy_Num INT PRIMARY KEY AUTO_INCREMENT,
    Policy_Name VARCHAR(100),
    Start_Date DATE,
    End_Date DATE,
    Insurance_Type VARCHAR(50),
    Plate_Num VARCHAR(20),
    FOREIGN KEY (Plate_Num) REFERENCES REGISTRATION(Plate_Num)
    	ON DELETE CASCADE
        ON UPDATE CASCADE
);